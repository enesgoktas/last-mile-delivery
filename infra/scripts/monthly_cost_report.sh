#!/usr/bin/env bash
set -euo pipefail

if [[ $# -lt 2 || $# -gt 3 ]]; then
  cat <<'USAGE'
Usage:
  monthly_cost_report.sh <start-date> <end-date> [output-file]

Example:
  monthly_cost_report.sh 2026-02-01 2026-03-01 docs/operations/reports/2026-02.md
USAGE
  exit 1
fi

START_DATE="$1"
END_DATE="$2"
OUTPUT_FILE="${3:-}"
INPUT_JSON_FILE="${COST_REPORT_INPUT_JSON:-}"

if [[ ! "${START_DATE}" =~ ^[0-9]{4}-[0-9]{2}-[0-9]{2}$ ]]; then
  echo "start-date must be in YYYY-MM-DD format." >&2
  exit 1
fi
if [[ ! "${END_DATE}" =~ ^[0-9]{4}-[0-9]{2}-[0-9]{2}$ ]]; then
  echo "end-date must be in YYYY-MM-DD format." >&2
  exit 1
fi
if [[ "${START_DATE}" > "${END_DATE}" || "${START_DATE}" == "${END_DATE}" ]]; then
  echo "start-date must be before end-date." >&2
  exit 1
fi

if ! command -v jq >/dev/null 2>&1; then
  echo "jq is required." >&2
  exit 1
fi

if [[ -n "${INPUT_JSON_FILE}" ]]; then
  if [[ ! -f "${INPUT_JSON_FILE}" ]]; then
    echo "COST_REPORT_INPUT_JSON file not found: ${INPUT_JSON_FILE}" >&2
    exit 1
  fi
  RAW_JSON="$(cat "${INPUT_JSON_FILE}")"
else
  if ! command -v aws >/dev/null 2>&1; then
    echo "aws CLI is required when COST_REPORT_INPUT_JSON is not provided." >&2
    exit 1
  fi
  RAW_JSON="$(aws ce get-cost-and-usage \
    --time-period Start="${START_DATE}",End="${END_DATE}" \
    --granularity MONTHLY \
    --metrics UnblendedCost \
    --group-by Type=DIMENSION,Key=SERVICE \
    --output json)"
fi

TOTAL_COST="$(echo "${RAW_JSON}" | jq -r '.ResultsByTime[0].Total.UnblendedCost.Amount // "0"')"
TOP_SERVICES="$(echo "${RAW_JSON}" | jq -r '
  .ResultsByTime[0].Groups
  | map({
      service: .Keys[0],
      amount: (.Metrics.UnblendedCost.Amount | tonumber)
    })
  | sort_by(-.amount)
  | .[0:10]
')"

REPORT_CONTENT="$(cat <<EOF
# Monthly AWS Cost Report (${START_DATE} to ${END_DATE})

## Total Spend
- \$$(printf "%.2f" "${TOTAL_COST}")

## Top Services
| Service | Cost (USD) |
|---|---:|
$(echo "${TOP_SERVICES}" | jq -r '.[] | "| \(.service) | \(.amount | tostring) |"')

## Notes
- Generated by \`infra/scripts/monthly_cost_report.sh\`.
- Data source: AWS Cost Explorer \`UnblendedCost\`.
EOF
)"

if [[ -n "${OUTPUT_FILE}" ]]; then
  mkdir -p "$(dirname "${OUTPUT_FILE}")"
  printf "%s\n" "${REPORT_CONTENT}" > "${OUTPUT_FILE}"
  echo "Cost report written to ${OUTPUT_FILE}"
else
  printf "%s\n" "${REPORT_CONTENT}"
fi
